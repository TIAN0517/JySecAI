// S2T 將簡體中文字符串轉換為繁體中文。
// 只處理映射表中的字,其餘字元(含繁體、英文、數字)原樣保留。
func S2T(s string) string {
	if s == "" {
		return s
	}
	buf := make([]rune, 0, len(s))
	for _, r := range s {
		if t, ok := simplifiedToTraditional[r]; ok {
			buf = append(buf, t)
		} else {
			buf = append(buf, r)
		}
	}
	return string(buf)
}
